"""Step 2, train/test split for the dropout analysis. Fits no model.

Reads   Attachments/Student Dropout/data.csv (never modified)
Writes  Code/outputs/dropout/02_split.csv   (one row per student: row_id, split, y)
        Code/outputs/dropout/02_split.md    (counts, seed, checksum of the split file)

The test set (split = "test") is locked: no script may read it until the single final evaluation.

Rule (DR-09, DR-10): random split, 20% test, stratified by y (Dropout = 1), seed 2026.
Admissibility 3 answered "one row per student", so no group column is used.

Run:    cd Code && uv run python dropout/02_split.py
"""
import hashlib
from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

SEED = 2026
TEST_FRACTION = 0.20

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
OUT_DIR = ROOT / "Code" / "outputs" / "dropout"
OUT_CSV = OUT_DIR / "02_split.csv"
OUT_MD = OUT_DIR / "02_split.md"

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
n = len(df)

# y: 1 = Dropout; Graduate and Enrolled are 0 (DR-08)
y = (df["Target"] == "Dropout").astype(int)
row_id = pd.Series(range(1, n + 1), name="row_id")  # 1-based data row in the file

idx_train, idx_test = train_test_split(
    row_id.index, test_size=TEST_FRACTION, stratify=y, random_state=SEED, shuffle=True
)

split = pd.Series("", index=row_id.index, name="split")
split.loc[idx_train] = "train"
split.loc[idx_test] = "test"

out = pd.DataFrame({"row_id": row_id, "split": split, "y": y})
OUT_DIR.mkdir(parents=True, exist_ok=True)
out.to_csv(OUT_CSV, index=False, lineterminator="\n")

csv_sha = hashlib.sha256(OUT_CSV.read_bytes()).hexdigest()

counts = out.groupby("split").agg(rows=("y", "size"), dropout=("y", "sum"))
counts["share_dropout"] = counts["dropout"] / counts["rows"]

lines = []
add = lines.append
add("# Step 2 split: Student Dropout")
add("")
add("Generated by `Code/dropout/02_split.py`. Fits no model.")
add("")
add(f"- Source: `Attachments/Student Dropout/data.csv`, {n:,} rows.")
add(f"- Rule: random split, test fraction {TEST_FRACTION:.0%}, stratified by y (Dropout = 1), seed {SEED}. No groups: Admissibility 3 answered one row per student (DR-02).")
add(f"- Output: `Code/outputs/dropout/02_split.csv`, SHA-256 `{csv_sha}`.")
add("- The test set is locked: no step before the final evaluation reads rows with split = test.")
add("")
add("| Split | Rows | Dropout (y = 1) | Share Dropout |")
add("| --- | ---: | ---: | ---: |")
for s in ["train", "test"]:
    r = counts.loc[s]
    add(f"| {s} | {int(r['rows']):,} | {int(r['dropout']):,} | {r['share_dropout']:.1%} |")
add(f"| all | {n:,} | {int(out['y'].sum()):,} | {out['y'].mean():.1%} |")
add("")
OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")

print(counts.to_string())
print(f"seed={SEED} test_fraction={TEST_FRACTION} csv_sha256={csv_sha}")
