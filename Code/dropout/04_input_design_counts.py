"""Step 3, input design: counts under the rare-level grouping chosen by the user (DR-13). Fits no model.

Rule: within each categorical input, a level with fewer than RARE_MIN training students is grouped into
one "other" level. Counts use the training rows only (split = train). The grouping itself is applied
inside each fold or fit by the core (REQ-1), not here.

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/02_split.csv
Writes  Code/outputs/dropout/04_input_design.md
        Code/outputs/dropout/04_input_design.csv

Run     cd Code && uv run python dropout/04_input_design_counts.py
"""
from pathlib import Path

import pandas as pd

RARE_MIN = 10  # user's choice (DR-13): levels with fewer than 10 training students are grouped

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout"

CATEGORICAL = [
    "Marital status",
    "Application mode",
    "Course",
    "Previous qualification",
    "Nacionality",
    "Mother's qualification",
    "Father's qualification",
    "Mother's occupation",
    "Father's occupation",
]

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
assert len(split) == len(df)
tr = df.loc[(split["split"] == "train").values]
numeric = [c for c in df.columns if c not in CATEGORICAL and c != "Target"]

rows = []
for c in CATEGORICAL:
    vc = tr[c].value_counts()
    kept = int((vc >= RARE_MIN).sum())
    rare = int((vc < RARE_MIN).sum())
    other = 1 if rare > 0 else 0
    cols = kept + other
    rows.append({
        "input": c,
        "levels_before": int(len(vc)),
        "levels_kept": kept,
        "levels_grouped_into_other": rare,
        "students_in_other": int(vc[vc < RARE_MIN].sum()),
        "columns_after_grouping": cols,
    })
table = pd.DataFrame(rows)
total_before = int(table["levels_before"].sum())
total_after = int(table["columns_after_grouping"].sum())
n_inputs_after = len(numeric) + total_after
n_train = len(tr)

table.to_csv(OUT / "04_input_design.csv", index=False, lineterminator="\n")

lines = []
add = lines.append
add("# Step 3: input design counts (rare-level grouping, DR-13)")
add("")
add("Generated by `Code/dropout/04_input_design_counts.py`. Fits no model. Training rows only.")
add("")
add(f"- Rule: levels with fewer than {RARE_MIN} training students are grouped into one \"other\" level, within each categorical input (user's choice, DR-13).")
add(f"- Training rows: {n_train:,}.")
add(f"- Numeric inputs (including 0/1 flags): {len(numeric)}.")
add(f"- Categorical levels before grouping: {total_before}; one column per level after grouping: {total_after}.")
add(f"- Inputs after encoding under the rule: {len(numeric)} + {total_after} = {n_inputs_after} (before grouping: {len(numeric)} + {total_before} = {len(numeric) + total_before}).")
add(f"- Property 2 data-to-parameter ratio: {n_train:,} / ({n_inputs_after} + 1) = {n_train / (n_inputs_after + 1):.1f}.")
add("")
add("| Input | Levels before | Kept (at least 10 students) | Grouped into other | Students in other | Columns after |")
add("| --- | ---: | ---: | ---: | ---: | ---: |")
for r in rows:
    add(f"| {r['input']} | {r['levels_before']} | {r['levels_kept']} | {r['levels_grouped_into_other']} | {r['students_in_other']} | {r['columns_after_grouping']} |")
add("")
OUT.joinpath("04_input_design.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(table.to_string(index=False))
print(f"numeric={len(numeric)} categorical_before={total_before} categorical_after={total_after} inputs_after={n_inputs_after} property2={n_train / (n_inputs_after + 1):.2f}")
