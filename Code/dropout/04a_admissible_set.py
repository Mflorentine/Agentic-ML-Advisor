"""Step 4a: the admissible set for the dropout analysis. Uses the training rows only; fits nothing.

Property values come from the latest PROP records (DR-12, DR-14) and DR-11 for Properties 1, 4-8.
Must-haves come from the user's answers (DR-15).
The design rank check (MOD-2) is computed on the training rows, with rare levels grouped as in DR-13.

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/02_split.csv
Uses    Code/dropout/admissible.py (interim core, not reviewed)
Writes  Code/outputs/dropout/04a_admissible_set.json
        Code/outputs/dropout/04a_admissible_set.md

Run     cd Code && uv run python dropout/04a_admissible_set.py
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import admissible  # noqa: E402

SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout"

RARE_MIN = 10  # DR-13
CATEGORICAL = [
    "Marital status", "Application mode", "Course", "Previous qualification", "Nacionality",
    "Mother's qualification", "Father's qualification", "Mother's occupation", "Father's occupation",
]
MUST_HAVES = ["Property 6: probabilities = yes"]  # DR-15

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
assert len(split) == len(df)
tr = df.loc[(split["split"] == "train").values].reset_index(drop=True)
n_train = len(tr)
assert n_train == 3539

y = (tr["Target"] == "Dropout").astype(int)
numeric = [c for c in tr.columns if c not in CATEGORICAL and c != "Target"]

# Design under DR-13: rare levels (fewer than RARE_MIN training students) grouped into "other"
blocks = [np.ones((n_train, 1))]  # intercept
names = ["intercept"]
for c in CATEGORICAL:
    vc = tr[c].value_counts()
    keep = set(vc[vc >= RARE_MIN].index)
    grouped = tr[c].where(tr[c].isin(keep), other="other")
    dummies = pd.get_dummies(grouped, prefix=c, dtype=float)
    blocks.append(dummies.values)
    names += list(dummies.columns)
for c in numeric:
    blocks.append(tr[[c]].astype(float).values)
    names.append(c)
X = np.hstack(blocks)
n_params = X.shape[1]                       # includes the intercept
rank = int(np.linalg.matrix_rank(X))
exact_collinearity = rank < n_params
params_ge_n_train = n_params >= n_train

core_sha = hashlib.sha256((HERE / "admissible.py").read_bytes()).hexdigest()
props = {
    "output_type": "binary",               # PROP, DR-08 / DR-11
    "separable": "no",                     # PROP, DR-12
    "n_train": n_train,
    "n_params": n_params,
    "rank": rank,
    "params_ge_n_train": params_ge_n_train,
    "exact_collinearity": exact_collinearity,
}
rows = admissible.admissible_set(props, MUST_HAVES)

result = {
    "core": "Code/dropout/admissible.py (interim core, not reviewed)",
    "core_sha256": core_sha,
    "must_haves": MUST_HAVES,
    "properties_used": props,
    "admissible_configurations": [r["configuration"] for r in rows if r["admissible"]],
    "rows": rows,
}
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "04a_admissible_set.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 4a: admissible set (ADMSET)",
    "",
    "Generated by `Code/dropout/04a_admissible_set.py` using `Code/dropout/admissible.py` (interim core, not reviewed).",
    "",
    f"- Core SHA-256: `{core_sha}`",
    f"- Must-haves: {', '.join(MUST_HAVES)} (user, DR-15).",
    f"- Design: {n_params} parameters including the intercept; rank {rank}; rank below parameter count: {exact_collinearity}; parameters at least n_train ({n_train}): {params_ge_n_train}.",
    "",
    "| Configuration | Admissible | Code | Reason |",
    "| --- | --- | --- | --- |",
]
for r in rows:
    lines.append(f"| {r['configuration']} | {'yes' if r['admissible'] else 'no'} | {r['code']} | {r['reason']} |")
lines.append("")
(OUT / "04a_admissible_set.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps({k: result[k] for k in ["core_sha256", "must_haves", "properties_used", "admissible_configurations"]}, indent=2))
for r in rows:
    print(f"{r['configuration']:22s} {'yes' if r['admissible'] else 'no ':3s} {r['code']:5s} {r['reason']}")
