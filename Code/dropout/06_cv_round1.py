"""Step 4c, round 1: cross-validation of the baseline and Logistic + L2 (SEQ-3). Training rows only; the test set is not read.

Protocol: ML Guide section 16 as amended (see Code/dropout/cv.py). Outer 10 stratified folds, seed 2026;
inner 5-fold grid search for lambda, degree (poly only), and the F2 threshold.

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/02_split.csv (training rows only)
Uses    Code/dropout/cv.py (interim core, not reviewed)
Writes  Code/outputs/dropout/06_cv_round1.csv   (one row per outer fold per configuration)
        Code/outputs/dropout/06_cv_round1.md    (CV table and margins)
        Code/outputs/dropout/06_cv_round1.json  (settings, core SHA-256)

Run     cd Code && uv run python dropout/06_cv_round1.py
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import cv  # noqa: E402

SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout"

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
assert len(split) == len(df)
train = (split["split"] == "train").values
tr = df.loc[train].reset_index(drop=True)
assert len(tr) == 3539, len(tr)

y = (tr["Target"] == "Dropout").astype(int)
X = tr.drop(columns=["Target"])
numeric = [c for c in X.columns if c not in cv.CATEGORICAL]
assert len(numeric) == 27, len(numeric)

base_rows = cv.run_outer(X, y, numeric, "Baseline")
l2_rows = cv.run_outer(X, y, numeric, "Logistic + L2")
table = pd.DataFrame(base_rows + l2_rows)
table.to_csv(OUT / "06_cv_round1.csv", index=False, lineterminator="\n")

core_sha = hashlib.sha256((HERE / "cv.py").read_bytes()).hexdigest()

b = table[table.configuration == "Baseline"].sort_values("fold")
l = table[table.configuration == "Logistic + L2"].sort_values("fold")
diff = l["F2_test"].values - b["F2_test"].values
margin_mean = float(diff.mean())
margin_sd = float(diff.std(ddof=1))

def summarise(t):
    return {
        "F2_mean": float(t["F2_test"].mean()),
        "F2_sd": float(t["F2_test"].std(ddof=1)),
        "E_train_mean": float(t["E_train"].mean()),
        "E_val_mean": float(t["E_val"].mean()),
    }

sb, sl = summarise(b), summarise(l)
mode_lam = l["lambda"].mode().iloc[0]
mode_thr = l["threshold"].mode().iloc[0]
rel_c2 = "clear" if margin_mean >= margin_sd else "not clear"

result = {
    "round": 1,
    "configurations": ["Baseline", "Logistic + L2"],
    "outer_folds": cv.OUTER_K,
    "inner_folds": cv.INNER_K,
    "seed": cv.SEED,
    "lambda_grid": cv.LAMBDAS,
    "threshold_grid": cv.THRESHOLDS,
    "core": "Code/dropout/cv.py (interim core, not reviewed)",
    "core_sha256": core_sha,
    "baseline": sb,
    "logistic_L2": sl,
    "margin_L2_minus_baseline_mean": margin_mean,
    "margin_L2_minus_baseline_sd": margin_sd,
    "C2_margin_over_baseline": rel_c2,
    "logistic_L2_chosen_lambda_mode": float(mode_lam),
    "logistic_L2_chosen_threshold_mode": float(mode_thr),
    "logistic_L2_lambda_per_fold": [float(v) for v in l["lambda"]],
    "logistic_L2_threshold_per_fold": [float(v) for v in l["threshold"]],
}
(OUT / "06_cv_round1.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 4c, round 1: cross-validation of the baseline and Logistic + L2",
    "",
    "Generated by `Code/dropout/06_cv_round1.py` using `Code/dropout/cv.py` (interim core, not reviewed).",
    "",
    f"- Core SHA-256: `{core_sha}`",
    f"- Outer folds: {cv.OUTER_K}, stratified and shuffled, seed {cv.SEED}; inner folds {cv.INNER_K}. Training rows only (3,539).",
    "",
    "| Configuration | Mean F2 (outer folds) | SD of F2 | Mean E_train | Mean E_val |",
    "| --- | ---: | ---: | ---: | ---: |",
    f"| Baseline (most common class) | {sb['F2_mean']:.4f} | {sb['F2_sd']:.4f} | {sb['E_train_mean']:.4f} | {sb['E_val_mean']:.4f} |",
    f"| Logistic + L2 | {sl['F2_mean']:.4f} | {sl['F2_sd']:.4f} | {sl['E_train_mean']:.4f} | {sl['E_val_mean']:.4f} |",
    "",
    f"- Margin of Logistic + L2 over the baseline (fold by fold): mean {margin_mean:.4f}, SD {margin_sd:.4f}. C2 (clear if the mean is at least one SD): {rel_c2}.",
    f"- Chosen L2 strength (most common across folds): {mode_lam:g}; chosen threshold (most common): {mode_thr:.2f}.",
    "",
    "| Fold | Baseline F2 | Logistic + L2 F2 | Difference | λ | Threshold |",
    "| ---: | ---: | ---: | ---: | ---: | ---: |",
]
for i in range(len(b)):
    fb, fl = b.iloc[i], l.iloc[i]
    lines.append(f"| {int(fb['fold'])} | {fb['F2_test']:.4f} | {fl['F2_test']:.4f} | {fl['F2_test'] - fb['F2_test']:+.4f} | {fl['lambda']:g} | {fl['threshold']:.2f} |")
lines.append("")
(OUT / "06_cv_round1.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps({k: result[k] for k in ["core_sha256", "baseline", "logistic_L2", "margin_L2_minus_baseline_mean", "margin_L2_minus_baseline_sd", "C2_margin_over_baseline", "logistic_L2_chosen_lambda_mode", "logistic_L2_chosen_threshold_mode"]}, indent=2))
