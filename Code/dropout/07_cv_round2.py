"""Step 4c-4d, round 2: cross-validation of Logistic + poly + L2 on the same outer folds as round 1. Training rows only.

Uses Code/dropout/cv.py (interim core, not reviewed, the same code approved for round 1).
Reads   Code/outputs/dropout/06_cv_round1.csv (baseline and Logistic + L2 rows)
        Attachments/Student Dropout/data.csv and Code/outputs/dropout/02_split.csv (training rows only)
Writes  Code/outputs/dropout/07_cv_round2.csv   (outer fold rows for all three configurations)
        Code/outputs/dropout/07_cv_round2.md    (CV table, margins, selection confidence factors C1 to C2)
        Code/outputs/dropout/07_cv_round2.json  (settings, core SHA-256)

Run     cd Code && uv run python dropout/07_cv_round2.py
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import cv  # noqa: E402

SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout"

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
train = (split["split"] == "train").values
tr = df.loc[train].reset_index(drop=True)
assert len(tr) == 3539, len(tr)
y = (tr["Target"] == "Dropout").astype(int)
X = tr.drop(columns=["Target"])
numeric = [c for c in X.columns if c not in cv.CATEGORICAL]

round1 = pd.read_csv(OUT / "06_cv_round1.csv")
poly_rows = cv.run_outer(X, y, numeric, "Logistic + poly + L2")
table = pd.concat([round1, pd.DataFrame(poly_rows)], ignore_index=True)
table.to_csv(OUT / "07_cv_round2.csv", index=False, lineterminator="\n")

core_sha = hashlib.sha256((HERE / "cv.py").read_bytes()).hexdigest()

configs = ["Baseline", "Logistic + L2", "Logistic + poly + L2"]
by = {c: table[table.configuration == c].sort_values("fold").reset_index(drop=True) for c in configs}
F2 = {c: by[c]["F2_test"].values for c in configs}


def summ(c):
    t = by[c]
    return {
        "F2_mean": float(t["F2_test"].mean()),
        "F2_sd": float(t["F2_test"].std(ddof=1)),
        "E_train_mean": float(t["E_train"].mean()),
        "E_val_mean": float(t["E_val"].mean()),
    }


def margin(a, b):
    d = F2[a] - F2[b]
    return float(d.mean()), float(d.std(ddof=1))


summary = {c: summ(c) for c in configs}
mg = {
    "L2_vs_baseline": margin("Logistic + L2", "Baseline"),
    "poly_vs_baseline": margin("Logistic + poly + L2", "Baseline"),
    "poly_vs_L2": margin("Logistic + poly + L2", "Logistic + L2"),
}
leader = max(["Logistic + L2", "Logistic + poly + L2"], key=lambda c: summary[c]["F2_mean"])
runner_up = "Logistic + poly + L2" if leader == "Logistic + L2" else "Logistic + L2"
lead_margin, lead_sd = margin(leader, runner_up)
c1 = "clear" if lead_margin >= lead_sd else ("moderate" if lead_margin >= 0.5 * lead_sd else "none")
c2_mean, c2_sd = mg["L2_vs_baseline"] if leader == "Logistic + L2" else mg["poly_vs_baseline"]
c2 = "clear" if c2_mean >= c2_sd else "not clear"

result = {
    "round": 2,
    "configurations": configs,
    "summary": summary,
    "margins_mean_sd": {k: {"mean": v[0], "sd": v[1]} for k, v in mg.items()},
    "leader": leader,
    "C1_margin_over_runner_up": c1,
    "C2_margin_over_baseline": c2,
    "outer_folds": cv.OUTER_K,
    "seed": cv.SEED,
    "core": "Code/dropout/cv.py (interim core, not reviewed)",
    "core_sha256": core_sha,
    "poly_lambda_per_fold": [float(v) for v in by["Logistic + poly + L2"]["lambda"]],
    "poly_degree_per_fold": [int(v) for v in by["Logistic + poly + L2"]["degree"]],
    "poly_threshold_per_fold": [float(v) for v in by["Logistic + poly + L2"]["threshold"]],
}
(OUT / "07_cv_round2.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 4c-4d, round 2: cross-validation of Logistic + poly + L2 on the same folds",
    "",
    "Generated by `Code/dropout/07_cv_round2.py` using `Code/dropout/cv.py` (interim core, not reviewed).",
    "",
    f"- Core SHA-256: `{core_sha}`",
    f"- Outer folds: {cv.OUTER_K}, stratified and shuffled, seed {cv.SEED}; the same folds for all three configurations.",
    "",
    "| Configuration | Mean F2 | SD of F2 | Mean E_train | Mean E_val |",
    "| --- | ---: | ---: | ---: | ---: |",
]
for c in configs:
    s = summary[c]
    lines.append(f"| {c} | {s['F2_mean']:.4f} | {s['F2_sd']:.4f} | {s['E_train_mean']:.4f} | {s['E_val_mean']:.4f} |")
lines += [
    "",
    "| Margin (fold by fold difference) | Mean | SD |",
    "| --- | ---: | ---: |",
    f"| Logistic + L2 minus baseline | {mg['L2_vs_baseline'][0]:+.4f} | {mg['L2_vs_baseline'][1]:.4f} |",
    f"| Logistic + poly + L2 minus baseline | {mg['poly_vs_baseline'][0]:+.4f} | {mg['poly_vs_baseline'][1]:.4f} |",
    f"| Logistic + poly + L2 minus Logistic + L2 | {mg['poly_vs_L2'][0]:+.4f} | {mg['poly_vs_L2'][1]:.4f} |",
    "",
    f"- Leader by mean F2: {leader}. C1 (margin over the runner-up): {c1}. C2 (margin over the baseline): {c2}.",
    "",
    "| Fold | Baseline F2 | Logistic + L2 F2 | Logistic + poly + L2 F2 | Poly λ | Poly degree | Poly threshold |",
    "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
]
pb = by["Logistic + poly + L2"]
for i in range(len(pb)):
    lines.append(
        f"| {int(pb.iloc[i]['fold'])} | {F2['Baseline'][i]:.4f} | {F2['Logistic + L2'][i]:.4f} | {F2['Logistic + poly + L2'][i]:.4f} | "
        f"{pb.iloc[i]['lambda']:g} | {int(pb.iloc[i]['degree'])} | {pb.iloc[i]['threshold']:.2f} |"
    )
lines.append("")
(OUT / "07_cv_round2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps({k: result[k] for k in ["summary", "margins_mean_sd", "leader", "C1_margin_over_runner_up", "C2_margin_over_baseline"]}, indent=2))
