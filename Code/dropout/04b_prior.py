"""Step 4b: prior ranking for the dropout analysis (ML Guide sections 13 and 15). Fits nothing.

Reads   Code/outputs/dropout/04a_admissible_set.json (ADMSET, DR-17)
Property values: PROP records DR-08, DR-11, DR-12, DR-14; must-have Property 6 (DR-15).
Uses    Code/dropout/prior.py (interim core, not reviewed)
Writes  Code/outputs/dropout/04b_prior.json and Code/outputs/dropout/04b_prior.md

Run     cd Code && uv run python dropout/04b_prior.py
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import prior  # noqa: E402

OUT = ROOT / "Code" / "outputs" / "dropout"
adm = json.loads((OUT / "04a_admissible_set.json").read_text(encoding="utf-8"))

# Admissible configurations, with their family, poly and L2 flags (from the ADMSET rows)
ADMISSIBLE = [
    {"configuration": r["configuration"], "family": r["family"], "poly": r["poly"], "l2": r["l2"]}
    for r in adm["rows"] if r["admissible"]
]
assert [a["configuration"] for a in ADMISSIBLE] == adm["admissible_configurations"]

# Property values from the latest PROP records (DR-08, DR-11, DR-12, DR-14)
VALUES = {
    "Property 1": "binary",          # no matrix row for binary
    "Property 2": "ample",           # matrix row only for limited
    "Property 3": "many",            # DR-14: 130 inputs after encoding
    "Property 4": "low",             # DR-05: 25% categorical
    "Property 5": "none",            # DR-09: no requirement
    "Property 6": "yes",             # DR-09, DR-15: must-have
    "Property 7": "no",              # DR-09
    "Property 8": "unknown",         # DR-09: no expectation stated
    "Property 9": "no",              # DR-12
    "Property 10": "balanced",       # DR-12
}
MUST_HAVES = {"Property 6"}          # DR-15

ranked = prior.rank(ADMISSIBLE, VALUES, MUST_HAVES)
simple_first = "Logistic + L2"       # SEQ-2: plain Logistic is excluded (MOD-2), so its +L2 version
kept = prior.keep(ranked, simple_first)

core_sha = hashlib.sha256((HERE / "prior.py").read_bytes()).hexdigest()
result = {
    "core": "Code/dropout/prior.py (interim core, not reviewed)",
    "core_sha256": core_sha,
    "admissible_source": "Code/outputs/dropout/04a_admissible_set.json",
    "values": VALUES,
    "must_haves": sorted(MUST_HAVES),
    "ranking": [{"configuration": r["configuration"], "score": r["score"], "rank": r["rank"],
                 "entries": r["entries"]} for r in ranked],
    "simple_first_SEQ2": simple_first,
    "kept": kept["kept"],
    "DISF": kept["DISF"],
}
(OUT / "04b_prior.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 4b: prior ranking (PRIOR)",
    "",
    "Generated by `Code/dropout/04b_prior.py` using `Code/dropout/prior.py` (interim core, not reviewed).",
    "",
    f"- Core SHA-256: `{core_sha}`",
    f"- Admissible set: {', '.join(adm['admissible_configurations'])} (`Code/outputs/dropout/04a_admissible_set.json`).",
    f"- Simple-first (SEQ-2): {simple_first}. Baseline (SEQ-1): most common training class.",
    "",
    "| Rank | Configuration | Score | Matrix entries scored |",
    "| ---: | --- | ---: | --- |",
]
for r in ranked:
    ent = "; ".join(f"{e['property']} = {e['value']} → {e['column']} {e['score']:+d} {e['tag']}" for e in r["entries"]) or "none"
    lines.append(f"| {r['rank']} | {r['configuration']} | {r['score']:+d} | {ent} |")
lines += [
    "",
    f"- Kept: {', '.join(kept['kept'])}.",
    f"- DISF (not kept): {', '.join(kept['DISF']) if kept['DISF'] else 'none'}.",
    "",
]
(OUT / "04b_prior.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps({k: result[k] for k in ["core_sha256", "ranking", "kept", "DISF"]}, indent=2))
