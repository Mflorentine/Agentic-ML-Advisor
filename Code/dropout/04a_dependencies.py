"""Step 4a diagnostic: which columns of the training design are linearly dependent. Fits no model.

Builds the same design as 04a_admissible_set.py (rare levels grouped as in DR-13, intercept, one-hot
columns, numeric inputs), then adds columns in order; a column that adds no rank is reported with the
earlier columns it is a combination of.

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/02_split.csv (training rows only)
Writes  Code/outputs/dropout/04a_dependencies.md

Run     cd Code && uv run python dropout/04a_dependencies.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

RARE_MIN = 10  # DR-13
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout" / "04a_dependencies.md"

CAT = ["Marital status", "Application mode", "Course", "Previous qualification", "Nacionality",
       "Mother's qualification", "Father's qualification", "Mother's occupation", "Father's occupation"]

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
tr = df.loc[(split["split"] == "train").values].reset_index(drop=True)

blocks, names = [np.ones((len(tr), 1))], ["intercept"]
for c in CAT:
    vc = tr[c].value_counts()
    keep = set(vc[vc >= RARE_MIN].index)
    g = tr[c].where(tr[c].isin(keep), other="other")
    d = pd.get_dummies(g, prefix=c, dtype=float)
    blocks.append(d.values)
    names += list(d.columns)
numeric = [c for c in tr.columns if c not in CAT and c != "Target"]
for c in numeric:
    blocks.append(tr[[c]].astype(float).values)
    names.append(c)
X = np.hstack(blocks)
rank = int(np.linalg.matrix_rank(X))

kept, dep = [], []
for j in range(X.shape[1]):
    trial = kept + [j]
    if np.linalg.matrix_rank(X[:, trial]) == len(trial):
        kept.append(j)
    else:
        dep.append(j)

lines = [
    "# Step 4a diagnostic: linear dependencies in the training design",
    "",
    "Generated by `Code/dropout/04a_dependencies.py`. Fits no model. Training rows only; rare levels grouped as in DR-13.",
    "",
    f"- Columns including the intercept: {X.shape[1]}; rank: {rank}; dependent columns: {len(dep)}.",
    "",
    "| Dependent column | Residual of its fit on earlier columns | Combination of earlier columns (largest coefficients) |",
    "| --- | --- | --- |",
]
for j in dep:
    coef, *_ = np.linalg.lstsq(X[:, kept], X[:, j], rcond=None)
    resid = float(np.linalg.norm(X[:, kept] @ coef - X[:, j]))
    big = [f"{names[kept[i]]} ({coef[i]:+.0f})" for i in np.argsort(-np.abs(coef)) if abs(coef[i]) > 1e-6][:4]
    lines.append(f"| {names[j]} | {resid:.1e} | {', '.join(big)} |")
lines.append("")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
