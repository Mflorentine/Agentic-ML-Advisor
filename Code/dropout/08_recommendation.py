"""Step 4f: learning curve (C3), final tuning on all training data, and the recommendation (ML Guide sections 17 and 19).

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/07_cv_round2.csv (all three configurations, same outer folds)
        Code/outputs/dropout/04a_admissible_set.json (ADMSET)
Uses    Code/dropout/recommend.py and Code/dropout/cv.py (interim cores, not reviewed)
Writes  Code/outputs/dropout/08_learning_curve.csv
        Code/outputs/dropout/08_recommendation.md
        Code/outputs/dropout/08_recommendation.json

Training rows only; the test set is not read.
Run     cd Code && uv run python dropout/08_recommendation.py
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import cv  # noqa: E402
import recommend  # noqa: E402

SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT = ROOT / "Code" / "outputs" / "dropout"

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
tr = df.loc[(split["split"] == "train").values].reset_index(drop=True)
assert len(tr) == 3539
y = (tr["Target"] == "Dropout").astype(int)
X = tr.drop(columns=["Target"])
numeric = [c for c in X.columns if c not in cv.CATEGORICAL]

round2 = pd.read_csv(OUT / "07_cv_round2.csv")
r = {c: round2[round2.configuration == c].sort_values("fold").reset_index(drop=True)
     for c in ["Baseline", "Logistic + L2", "Logistic + poly + L2"]}

# 1-2. Learning curve for the leading configuration and C3
l2_round1 = round2[round2.configuration == "Logistic + L2"]
curve = recommend.learning_curve(X, y, numeric, round2)
curve.to_csv(OUT / "08_learning_curve.csv", index=False, lineterminator="\n")
c3 = recommend.c3(curve)

# 3. Final tuning on all training rows (for the test refit at 4g)
final = recommend.final_tuning(X, y, numeric)

# 4. Section 19 and 17 on the two admissible configurations
F2 = {c: r[c]["F2_test"].values for c in r}
def margin(a, b):
    d = F2[a] - F2[b]
    return float(d.mean()), float(d.std(ddof=1))

summary = {}
leader = max(["Logistic + L2", "Logistic + poly + L2"], key=lambda c: r[c]["F2_test"].mean())
other = "Logistic + poly + L2" if leader == "Logistic + L2" else "Logistic + L2"
lm, lsd = margin(leader, other)
for c in ["Logistic + L2", "Logistic + poly + L2"]:
    m_base, sd_base = margin(c, "Baseline")
    m_best, sd_best = margin(c, leader)   # margin to the best CV mean (0 for the leader)
    if c == leader:
        c1 = "clear" if lm >= lsd else ("moderate" if lm >= 0.5 * lsd else "none")
    else:
        c1 = "clear" if -lm >= lsd else ("moderate" if -lm >= 0.5 * lsd else "none")
    summary[c] = {
        "F2_mean": float(r[c]["F2_test"].mean()),
        "C1": c1,
        "C2": "clear" if m_base >= sd_base else "not clear",
        "margin_to_best_sd_ratio": (abs(m_best) / sd_best) if c != leader and sd_best > 0 else 0.0,
    }
prior_scores = {"Logistic + L2": 0, "Logistic + poly + L2": -1}   # DR-18
add_ons = {"Logistic + L2": 0, "Logistic + poly + L2": 1}          # poly is one add-on
rec = recommend.recommend(summary, c3["C3"], prior_scores, add_ons)

core_hashes = {f: hashlib.sha256((HERE / f).read_bytes()).hexdigest() for f in ["cv.py", "recommend.py"]}
result = {
    "learning_curve_C3": c3,
    "final_tuning_all_training_rows": {k: (float(v) if isinstance(v, (int, float, np.floating)) else v) for k, v in final.items()},
    "section_19_17": rec,
    "summary": summary,
    "margin_leader_minus_other": {"mean": lm, "sd": lsd},
    "core_sha256": core_hashes,
}
(OUT / "08_recommendation.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 4f: learning curve, final tuning and recommendation",
    "",
    "Generated by `Code/dropout/08_recommendation.py` using `Code/dropout/recommend.py` and `Code/dropout/cv.py` (interim cores, not reviewed).",
    "",
    f"- Core SHA-256: cv.py `{core_hashes['cv.py']}`; recommend.py `{core_hashes['recommend.py']}`",
    "",
    "## Learning curve (C3)",
    "",
    f"- Mean validation error at 80%: {c3['E_val_80_mean']:.4f}; at 100%: {c3['E_val_100_mean']:.4f}.",
    f"- Drop from 80% to 100%: {c3['drop_80_to_100']:+.4f}; threshold 0.5 × fold SD at 100% = {c3['threshold']:.4f}.",
    f"- C3: {c3['C3']}.",
    "",
    "## Final tuning on all training rows (for the test refit at 4g)",
    "",
    f"- L2 strength {final['lambda']:g}; F2 threshold {final['threshold']:.2f}; inner mean F2 {final['inner_mean_F2']:.4f}.",
    "",
    "## Section 19 recommendation and section 17 confidence",
    "",
    f"- Eligible (C2 clear, requirements met): {', '.join(rec['eligible']) or 'none'}.",
    f"- Best CV mean: {rec['best_CV_mean']}. Candidates: {', '.join(rec['candidates'])}.",
    f"- Chosen (fewest add-ons, then prior score, then CV mean): {rec['chosen']}.",
    f"- C1 (margin over the runner-up): {rec['C1']}. C2 (margin over the baseline): {rec['C2']}. C3: {rec['C3']}.",
    f"- Selection confidence: {rec['confidence']}.",
    "",
]
(OUT / "08_recommendation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps(result, indent=2, default=str))
