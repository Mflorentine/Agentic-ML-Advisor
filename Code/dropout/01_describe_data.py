"""Step 1, describing pass for the dropout analysis: what is in the file, with no judgement about what it means.

Reads   Attachments/Student Dropout/data.csv (never modified)
Writes  Code/outputs/dropout/01_describe.md

Run:    cd Code && uv run python dropout/01_describe_data.py
"""
import hashlib
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
OUT = ROOT / "Code" / "outputs" / "dropout" / "01_describe.md"

raw = SRC.read_bytes()
sha256 = hashlib.sha256(raw).hexdigest()
n_crlf = raw.count(b"\r\n")
n_lf = raw.count(b"\n")
has_bom = raw.startswith(b"\xef\xbb\xbf")

# The file is semicolon-separated, UTF-8 with a byte-order mark.
df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
raw_columns = list(df.columns)
df.columns = [c.strip() for c in df.columns]
whitespace_columns = [repr(c) for c in raw_columns if c != c.strip()]

n_rows, n_cols = df.shape
target = "Target"
inputs = [c for c in df.columns if c != target]

lines = []
add = lines.append

add("# Step 1 describing pass: Student Dropout (`Attachments/Student Dropout/data.csv`)")
add("")
add("Generated by `Code/dropout/01_describe_data.py`. This pass describes the file only; it draws no conclusion about what the columns mean for the analysis.")
add("")
add("## File")
add("")
add(f"- Size: {len(raw):,} bytes")
add(f"- SHA-256: `{sha256}`")
add(f"- Line endings: {n_crlf:,} CRLF, {n_lf:,} LF (every line ends in CRLF)")
add(f"- Byte-order mark at start: {has_bom}")
add("- Delimiter: semicolon (`;`)")
add(f"- Header lines: 1; data rows: {n_rows:,}; columns: {n_cols} (of which {len(inputs)} are candidate inputs and `{target}` is the candidate target)")
add(f"- Column names with leading or trailing whitespace, as found in the header: {', '.join(whitespace_columns) if whitespace_columns else 'none'}")
add("")

add("## Missing values and duplicates")
add("")
n_missing_cells = int(df.isna().sum().sum())
n_missing_cols = int((df.isna().sum() > 0).sum())
add(f"- Missing cells: {n_missing_cells:,}; columns with any missing value: {n_missing_cols}")
add(f"- Fully duplicated rows: {int(df.duplicated().sum()):,}")
add("")

add("## Candidate target")
add("")
counts = df[target].value_counts(dropna=False)
add("| Label | Rows | Share |")
add("| --- | ---: | ---: |")
for label, n in counts.items():
    add(f"| {label} | {n:,} | {n / n_rows:.1%} |")
add("")

add("## Columns")
add("")
add("Summary of every column as found. `unique` counts distinct non-missing values. For a column with 12 or fewer distinct values, the values and their counts are listed; for the rest, the range.")
add("")
add("| Column | dtype | missing | unique | range or values |")
add("| --- | --- | ---: | ---: | --- |")
for c in df.columns:
    s = df[c]
    n_unique = int(s.nunique(dropna=True))
    n_miss = int(s.isna().sum())
    if pd.api.types.is_numeric_dtype(s):
        if n_unique <= 12:
            vc = s.value_counts(dropna=True).sort_index()
            detail = ", ".join(f"{v:g}: {n}" for v, n in vc.items())
        else:
            detail = f"min {s.min():g}, max {s.max():g}"
    else:
        vc = s.value_counts(dropna=True)
        detail = ", ".join(f"{v}: {n}" for v, n in vc.items())
    add(f"| {c} | {s.dtype} | {n_miss} | {n_unique} | {detail} |")
add("")

add("## Numeric summary")
add("")
num = df[inputs].select_dtypes("number")
desc = num.describe().T[["mean", "std", "min", "50%", "max"]]
desc.columns = ["mean", "std", "min", "median", "max"]
add("| Column | mean | std | min | median | max |")
add("| --- | ---: | ---: | ---: | ---: | ---: |")
for c, r in desc.iterrows():
    add(f"| {c} | {r['mean']:.4g} | {r['std']:.4g} | {r['min']:.4g} | {r['median']:.4g} | {r['max']:.4g} |")
add("")

add("## Inputs after encoding (counts only)")
add("")
# Categorical inputs as decided by the user in step 1 (DR-04): the columns with code lists,
# plus the two parents' occupation codes. Yes/no flags and the other counts stay numeric (0/1).
CATEGORICAL = [
    "Marital status",
    "Application mode",
    "Course",
    "Previous qualification",
    "Nacionality",
    "Mother's qualification",
    "Father's qualification",
    "Mother's occupation",
    "Father's occupation",
]
missing_cat = [c for c in CATEGORICAL if c not in inputs]
assert not missing_cat, f"categorical columns not found: {missing_cat}"
non_numeric = [c for c in inputs if not pd.api.types.is_numeric_dtype(df[c])]
numeric_inputs = [c for c in inputs if c not in CATEGORICAL]
levels = {c: int(df[c].nunique(dropna=True)) for c in CATEGORICAL}
levels_total = sum(levels.values())
share_cat = len(CATEGORICAL) / len(inputs)
add(f"- Candidate inputs: {len(inputs)}; non-numeric (text) inputs: {len(non_numeric)}")
add(f"- Categorical inputs (user's decision, DR-04): {len(CATEGORICAL)} of {len(inputs)}, a share of {share_cat:.1%} of the original input columns.")
add(f"- Numeric inputs (including 0/1 flags): {len(numeric_inputs)}.")
add("- Observed levels per categorical input, one one-hot column per level: " + ", ".join(f"{c} {levels[c]}" for c in CATEGORICAL) + f". Total {levels_total} levels.")
add(f"- Inputs after one-hot encoding, one column per observed level, no column dropped: {len(numeric_inputs)} + {levels_total} = {len(numeric_inputs) + levels_total}. The count drops by one per categorical input if one level is dropped to avoid collinearity; the choice is made in the core, not here.")
add("- The categorical share and the encoded count are counts of the file, not property values. Property 2: data-to-parameter ratio needs the training size, so it is computed after the split (step 2).")
add("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}")
print(f"rows={n_rows} cols={n_cols} sha256={sha256}")
print(counts.to_string())
