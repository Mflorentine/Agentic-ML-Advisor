"""Step 3: Properties 9 and 10 for the dropout analysis, from the training rows only.

Reads   Attachments/Student Dropout/data.csv (never modified)
        Code/outputs/dropout/02_split.csv (split = train rows only are used)
Writes  Code/outputs/dropout/03_props_9_10.json
        Code/outputs/dropout/03_props_9_10.md

Uses    Code/dropout/core.py (interim core, not reviewed). Its SHA-256 is written to the output.
Run     cd Code && uv run python dropout/03_properties_9_10.py
"""
import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import core  # noqa: E402  (the interim core in this folder)

SRC = ROOT / "Attachments" / "Student Dropout" / "data.csv"
SPLIT = ROOT / "Code" / "outputs" / "dropout" / "02_split.csv"
OUT_DIR = ROOT / "Code" / "outputs" / "dropout"

df = pd.read_csv(SRC, sep=";", encoding="utf-8-sig")
df.columns = [c.strip() for c in df.columns]
split = pd.read_csv(SPLIT)
assert len(split) == len(df), "split file and data disagree on row count"
assert (split["row_id"].values == range(1, len(df) + 1)).all(), "split rows not in file order"

y = (df["Target"] == "Dropout").astype(int)
X = df.drop(columns=["Target"])

train = (split["split"] == "train").values
X_train, y_train = X.loc[train].reset_index(drop=True), y.loc[train].reset_index(drop=True)
assert len(y_train) == 3539, f"training rows: {len(y_train)}"

p10 = core.property_10_imbalance(y_train)
p9 = core.property_9_separable(X_train, y_train, seed=2026)

core_sha = hashlib.sha256((HERE / "core.py").read_bytes()).hexdigest()
result = {
    "core": "Code/dropout/core.py (interim core, not reviewed)",
    "core_sha256": core_sha,
    "training_rows": int(len(y_train)),
    "properties": [p9, p10],
}
(OUT_DIR / "03_props_9_10.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

lines = [
    "# Step 3: Properties 9 and 10 (training rows only)",
    "",
    "Generated by `Code/dropout/03_properties_9_10.py` using `Code/dropout/core.py` (interim core, not reviewed).",
    "",
    f"- Core SHA-256: `{core_sha}`",
    f"- Training rows used: {len(y_train):,}. The test rows are not read.",
    "",
    "| Property | Value | Measure | Threshold [I] | Evidence |",
    "| --- | --- | --- | --- | --- |",
    f"| Property 10: class imbalance | {p10['value']} | smallest class {p10['smallest_class_share']:.1%} of training rows (Graduate or Enrolled {p10['class_counts']['0']:,}; Dropout {p10['class_counts']['1']:,}) | smallest class below {p10['threshold']:.0%} | T |",
    f"| Property 9: classes perfectly separable | {p9['value']} | training accuracy {p9['training_accuracy']:.4f}; solver iterations {p9['solver_iterations']} of {p9['max_iter']} | training accuracy at least {p9['threshold']:.0%} | T |",
    "",
]
(OUT_DIR / "03_props_9_10.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print(json.dumps(result, indent=2))
